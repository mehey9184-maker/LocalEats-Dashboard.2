CREATE OR REPLACE VIEW public.rider_status_view AS
SELECT 
    rc.id as connection_id,
    rc.shop_id,
    rc.rider_id,
    COALESCE(rp.full_name, rc.rider_name) as rider_name,
    COALESCE(rp.is_online, false) as is_online,
    COALESCE(rp.status, 'offline') as status,
    rc.expires_at,
    rc.connection_code,
    CASE 
        WHEN rc.expires_at < now() THEN 'expired'
        WHEN rp.is_online = true THEN 'online'
        ELSE 'offline'
    END as status_derived
FROM public.rider_connections rc
LEFT JOIN public.rider_profiles rp ON rc.rider_id = rp.id;

CREATE OR REPLACE FUNCTION public.nudge_rider(rider_id UUID, message TEXT)
RETURNS VOID AS $$
DECLARE
    merchant_shop_id BIGINT;
BEGIN
    SELECT id INTO merchant_shop_id FROM public.shops WHERE owner_id::text = (SELECT auth.uid())::text LIMIT 1;
    INSERT INTO public.rider_notifications (rider_id, shop_id, message, type)
    VALUES (rider_id, merchant_shop_id, message, 'nudge');
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

CREATE OR REPLACE FUNCTION public.nudge_rider_by_id(
    target_rider_id UUID, 
    target_shop_id BIGINT, 
    nudge_message TEXT DEFAULT 'Wake up! New order incoming.'
)
RETURNS VOID AS $$
BEGIN
    INSERT INTO public.rider_notifications (rider_id, shop_id, message, type)
    VALUES (target_rider_id, target_shop_id, nudge_message, 'nudge');
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

