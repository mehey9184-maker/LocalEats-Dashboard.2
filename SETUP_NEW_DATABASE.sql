-- 0. Enable PostGIS for geospatial capabilities
CREATE EXTENSION IF NOT EXISTS postgis;

-- 1. SHOPS TABLE
CREATE TABLE IF NOT EXISTS public.shops (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  name TEXT NOT NULL,
  email TEXT,
  phone TEXT,
  address TEXT,
  city TEXT,
  is_active BOOLEAN DEFAULT true,
  lat NUMERIC,
  lng NUMERIC,
  delivery_fee NUMERIC DEFAULT 15.00,
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now()
);

-- 2. MENU ITEMS TABLE
CREATE TABLE IF NOT EXISTS public.menu_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shop_id BIGINT REFERENCES public.shops(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  price NUMERIC NOT NULL DEFAULT 0.00,
  description TEXT,
  category TEXT DEFAULT 'General',
  image_url TEXT,
  is_available BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 3. RIDER PROFILES TABLE
CREATE TABLE IF NOT EXISTS public.rider_profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  full_name TEXT,
  name TEXT,
  phone TEXT,
  is_online BOOLEAN DEFAULT false,
  status TEXT DEFAULT 'offline',
  vehicle_type TEXT DEFAULT 'Road',
  verification_status TEXT DEFAULT 'approved',
  rating NUMERIC DEFAULT 5.0,
  current_latitude NUMERIC,
  current_longitude NUMERIC,
  total_earnings NUMERIC DEFAULT 0,
  total_deliveries INTEGER DEFAULT 0,
  active_points INTEGER DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now()
);

-- 4. RIDER CONNECTIONS TABLE (HANDSHAKE PAIRING)
CREATE TABLE IF NOT EXISTS public.rider_connections (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  shop_id BIGINT REFERENCES public.shops(id) ON DELETE CASCADE,
  rider_id UUID REFERENCES public.rider_profiles(id) ON DELETE SET NULL,
  rider_name TEXT,
  connection_code TEXT,
  status TEXT DEFAULT 'active',
  expires_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 5. ORDERS TABLE
CREATE TABLE IF NOT EXISTS public.orders (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  shop_id BIGINT REFERENCES public.shops(id) ON DELETE CASCADE,
  user_id UUID,
  rider_id UUID REFERENCES public.rider_profiles(id) ON DELETE SET NULL,
  product_name TEXT,
  product_variant TEXT,
  total_price NUMERIC NOT NULL DEFAULT 0.00,
  price NUMERIC,
  status TEXT DEFAULT 'pending',
  delivery_status TEXT DEFAULT 'pending',
  payment_method TEXT DEFAULT 'cash_on_delivery',
  customer_name TEXT,
  phone TEXT,
  email TEXT,
  address TEXT,
  city TEXT,
  lat NUMERIC,
  lng NUMERIC,
  merchant_rating NUMERIC,
  acceptance_message TEXT,
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now()
);

-- 6. ANNOUNCEMENTS TABLE
CREATE TABLE IF NOT EXISTS public.announcements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shop_id BIGINT REFERENCES public.shops(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  content TEXT NOT NULL,
  is_active BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 7. CHAT MESSAGES TABLE
CREATE TABLE IF NOT EXISTS public.chat_messages (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  shop_id BIGINT REFERENCES public.shops(id) ON DELETE CASCADE,
  order_id UUID REFERENCES public.orders(id) ON DELETE CASCADE,
  sender_id UUID,
  sender_role TEXT, -- 'merchant', 'rider', 'customer'
  message TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 8. PAYMENTS TABLE
CREATE TABLE IF NOT EXISTS public.payments (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  shop_id BIGINT REFERENCES public.shops(id) ON DELETE CASCADE,
  amount NUMERIC NOT NULL,
  payment_method TEXT NOT NULL, -- 'OTT', '1Voucher', 'Admin Code'
  transaction_id TEXT,
  status TEXT NOT NULL DEFAULT 'pending',
  payment_date TIMESTAMPTZ DEFAULT now()
);

-- 9. REVIEWS TABLE
CREATE TABLE IF NOT EXISTS public.reviews (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  shop_id BIGINT REFERENCES public.shops(id) ON DELETE CASCADE,
  order_id UUID REFERENCES public.orders(id) ON DELETE SET NULL,
  rating INTEGER CHECK (rating >= 1 AND rating <= 5),
  comment TEXT,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 10. RIDER NOTIFICATIONS TABLE
CREATE TABLE IF NOT EXISTS public.rider_notifications (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  rider_id UUID REFERENCES public.rider_profiles(id) ON DELETE CASCADE,
  shop_id BIGINT REFERENCES public.shops(id) ON DELETE SET NULL,
  message TEXT NOT NULL,
  type TEXT DEFAULT 'nudge',
  is_read BOOLEAN DEFAULT false,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 11. ERROR LOGGING TABLES
CREATE TABLE IF NOT EXISTS public.app_errors (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  error_message TEXT,
  stack TEXT,
  context JSONB,
  created_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.app_error_logs (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  message TEXT,
  details JSONB,
  created_at TIMESTAMPTZ DEFAULT now()
);

