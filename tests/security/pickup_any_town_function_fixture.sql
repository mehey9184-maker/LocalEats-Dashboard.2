-- Disposable PostgreSQL 17 fixture ONLY. This minimal schema is sufficient
-- to compile and exercise the EXACT reviewed zero-fee pickup function body.
-- No Supabase project, auth user, real shop/order or live token is involved.
create role anon nologin;
create role authenticated nologin;
create role service_role nologin bypassrls;
grant usage on schema public to service_role;

create table public.shops (
 id text primary key,
 name text not null,
 location text,
 approval_status text not null,
 is_active boolean not null,
 archived_at timestamptz,
 lat numeric,
 lng numeric,
 latitude numeric,
 longitude numeric
);
create table public.menu_items (
 id uuid primary key,
 shop_id text not null references public.shops(id),
 name text not null,
 price numeric not null,
 is_available boolean not null
);
create table public.orders (
 id uuid primary key default gen_random_uuid(),
 shop_id text not null,
 user_id text not null,
 product_name text,
 product_variant text,
 price numeric,
 total_price numeric,
 status text,
 delivery_status text,
 payment_method text,
 customer_name text,
 phone text,
 email text,
 address text,
 city text,
 lat numeric,
 lng numeric,
 notes text,
 delivery_fee numeric,
 service_fee numeric,
 discount_amount numeric,
 tip_amount numeric,
 idempotency_key text not null unique,
 items jsonb,
 delivery_type text,
 payment_status text,
 create_intent_hash text,
 revision integer,
 created_at timestamptz not null default now()
);
create table public.pickup_order_events (
 id bigint generated by default as identity primary key,
 order_id uuid not null references public.orders(id),
 revision integer not null,
 command_id uuid not null,
 command_hash text not null,
 kind text not null,
 actor_uid text not null
);
grant all on all tables in schema public to service_role;
grant all on all sequences in schema public to service_role;

